export const searchProducts = (query = '', categorySlug = 'all') => {
  return PRODUCTS.filter((product) => {
    const matchesCategory =
      !categorySlug || categorySlug === 'all' || product.categorySlug === categorySlug;
    const q = query.toLowerCase().trim();
    const matchesQuery =
      !q ||
      product.name.toLowerCase().includes(q) ||
      product.categoryName.toLowerCase().includes(q) ||
      product.fpoName.toLowerCase().includes(q) ||
      product.fpoLocation.toLowerCase().includes(q) ||
      product.farmerLead.toLowerCase().includes(q);
    return matchesCategory && matchesQuery;
  });
};

export const getProductById = (id) => {
  return PRODUCTS.find((p) => String(p.id) === String(id) || p.slug === String(id));
};
